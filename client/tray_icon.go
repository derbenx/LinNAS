// GetLnIcoBytes returns the bytes from ln.ico next to the binary if present, or embedded fallback
func GetLnIcoBytes() []byte {
	exePath, err := os.Executable()
	if err == nil {
		if resolved, rErr := filepath.EvalSymlinks(exePath); rErr == nil {
			exePath = resolved
		}
		diskIco := filepath.Join(filepath.Dir(exePath), "ln.ico")
		if data, dErr := os.ReadFile(diskIco); dErr == nil && len(data) > 0 {
			return data
		}
	}
	if data, err := os.ReadFile("ln.ico"); err == nil && len(data) > 0 {
		return data
	}
	return embeddedLnIco
}
