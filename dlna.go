func getMiniDLNAConfigPath() string {
	return filepath.Join(getBinaryDir(), "minidlna_linnas.conf")
}

func generateMiniDLNAConf(mediaFolder, friendlyName string, port int) string {
	if port <= 0 {
		port = 8200
	}
	dbDir := filepath.Join(getBinaryDir(), ".minidlna_db")
	_ = os.MkdirAll(dbDir, 0755)

	return fmt.Sprintf(`# Generated by LinNAS
port=%d
network_interface=
media_dir=A,%s
friendly_name=%s
db_dir=%s
log_dir=%s
album_art_names=Cover.jpg/cover.jpg/AlbumArtSmall.jpg/albumartsmall.jpg/AlbumArt.jpg/albumart.jpg/Album.jpg/album.jpg/Folder.jpg/folder.jpg
inotify=yes
enable_tivo=no
strict_dlna=no
notify_interval=60
serial=12345678
model_number=1
`, port, mediaFolder, friendlyName, dbDir, dbDir)
}

func isMiniDLNARunning() bool {
	out, err := exec.Command("pgrep", "-f", "minidlna").Output()
	return err == nil && len(strings.TrimSpace(string(out))) > 0
}

func startMiniDLNA(mediaFolder, friendlyName string, port int) error {
	_ = stopMiniDLNA()

	confContent := generateMiniDLNAConf(mediaFolder, friendlyName, port)
	confPath := getMiniDLNAConfigPath()
	if err := os.WriteFile(confPath, []byte(confContent), 0644); err != nil {
		return err
	}

	cmd := exec.Command("minidlna", "-f", confPath, "-R")
	if os.Getuid() != 0 {
		cmd = exec.Command("sudo", "-n", "minidlna", "-f", confPath, "-R")
	}
	if out, err := cmd.CombinedOutput(); err != nil {
		// Try system service fallback
		svcCmd := exec.Command("systemctl", "start", "minidlna")
		if os.Getuid() != 0 {
			svcCmd = exec.Command("sudo", "-n", "systemctl", "start", "minidlna")
		}
		if svcOut, svcErr := svcCmd.CombinedOutput(); svcErr != nil {
			return fmt.Errorf("failed starting minidlna: %v (%s / %s)", err, string(out), string(svcOut))
		}
	}
	time.Sleep(300 * time.Millisecond)
	return nil
}

func stopMiniDLNA() error {
	cmd := exec.Command("pkill", "-f", "minidlna")
	if os.Getuid() != 0 {
		cmd = exec.Command("sudo", "-n", "pkill", "-f", "minidlna")
	}
	_ = cmd.Run()

	svcCmd := exec.Command("systemctl", "stop", "minidlna")
	if os.Getuid() != 0 {
		svcCmd = exec.Command("sudo", "-n", "systemctl", "stop", "minidlna")
	}
	_ = svcCmd.Run()

	time.Sleep(200 * time.Millisecond)
	return nil
}

