func handleDLNAConfig(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		http.Error(w, "Method not allowed", http.StatusMethodNotAllowed)
		return
	}

	bodyBytes, err := io.ReadAll(r.Body)
	if err != nil {
		http.Error(w, "Failed to read body", http.StatusBadRequest)
		return
	}
	decryptedBody, err := decryptPayload(bodyBytes)
	if err != nil {
		http.Error(w, fmt.Sprintf(`{"error":"decryption_failed: %v"}`, err), http.StatusBadRequest)
		return
	}

	var req struct {
		ServerBackend *string `json:"server_backend"`
		MediaFolder   *string `json:"media_folder"`
		FriendlyName  *string `json:"friendly_name"`
		Port          *int    `json:"port"`
		StreamMode    *string `json:"stream_mode"`
	}
	if err := json.Unmarshal(decryptedBody, &req); err != nil {
		http.Error(w, "Invalid JSON data", http.StatusBadRequest)
		return
	}

	dlnaConfigMu.RLock()
	curCfg := dlnaConfig
	dlnaConfigMu.RUnlock()

	needRestart := false

	if req.ServerBackend != nil && (*req.ServerBackend == "builtin" || *req.ServerBackend == "minidlna") {
		if curCfg.ServerBackend != *req.ServerBackend {
			curCfg.ServerBackend = *req.ServerBackend
			needRestart = true
		}
	}

	if req.MediaFolder != nil && strings.TrimSpace(*req.MediaFolder) != "" {
		newFolder := filepath.Clean(strings.TrimSpace(*req.MediaFolder))
		if curCfg.MediaFolder != newFolder {
			curCfg.MediaFolder = newFolder
			needRestart = true
		}
	}

	if req.FriendlyName != nil && strings.TrimSpace(*req.FriendlyName) != "" {
		newName := strings.TrimSpace(*req.FriendlyName)
		if curCfg.FriendlyName != newName {
			curCfg.FriendlyName = newName
			needRestart = true
		}
	}

	if req.Port != nil && *req.Port > 1024 && *req.Port <= 65535 {
		if curCfg.Port != *req.Port {
			curCfg.Port = *req.Port
			needRestart = true
		}
	}

	if req.StreamMode != nil && (*req.StreamMode == "direct_http" || *req.StreamMode == "dlna_content") {
		curCfg.StreamMode = *req.StreamMode
	}

	if err := saveDLNAConfig(curCfg); err != nil {
		jsonResponse(w, map[string]interface{}{"success": false, "error": err.Error()})
		return
	}

	// Restart active server if running and config changed
	if curCfg.Enabled && needRestart {
		if curCfg.ServerBackend == "minidlna" {
			_ = stopBuiltinDLNAServer()
			_ = startMiniDLNA(curCfg.MediaFolder, curCfg.FriendlyName, curCfg.Port)
		} else {
			_ = stopMiniDLNA()
			_ = startBuiltinDLNAServer(curCfg.MediaFolder, curCfg.FriendlyName, curCfg.Port)
		}
	}

	jsonResponse(w, map[string]interface{}{
		"success": true,
		"config":  curCfg,
	})
}

func handleDLNAToggle(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		http.Error(w, "Method not allowed", http.StatusMethodNotAllowed)
		return
	}

	bodyBytes, err := io.ReadAll(r.Body)
	if err != nil {
		http.Error(w, "Failed to read body", http.StatusBadRequest)
		return
	}
	decryptedBody, err := decryptPayload(bodyBytes)
	if err != nil {
		http.Error(w, fmt.Sprintf(`{"error":"decryption_failed: %v"}`, err), http.StatusBadRequest)
		return
	}

	var req struct {
		Enabled bool `json:"enabled"`
	}
	if err := json.Unmarshal(decryptedBody, &req); err != nil {
		http.Error(w, "Invalid JSON data", http.StatusBadRequest)
		return
	}

	dlnaConfigMu.RLock()
	cfg := dlnaConfig
	dlnaConfigMu.RUnlock()

	cfg.Enabled = req.Enabled
	var opErr error

	if cfg.Enabled {
		// Ensure folder exists
		if cfg.MediaFolder == "" {
			jsonResponse(w, map[string]interface{}{"success": false, "error": "Media folder not configured"})
			return
		}
		if fi, err := os.Stat(cfg.MediaFolder); err != nil || !fi.IsDir() {
			_ = os.MkdirAll(cfg.MediaFolder, 0755)
		}

		if cfg.ServerBackend == "minidlna" {
			_ = stopBuiltinDLNAServer()
			opErr = startMiniDLNA(cfg.MediaFolder, cfg.FriendlyName, cfg.Port)
		} else {
			_ = stopMiniDLNA()
			opErr = startBuiltinDLNAServer(cfg.MediaFolder, cfg.FriendlyName, cfg.Port)
		}
	} else {
		if cfg.ServerBackend == "minidlna" {
			opErr = stopMiniDLNA()
		} else {
			opErr = stopBuiltinDLNAServer()
		}
	}

	if opErr != nil {
		cfg.Enabled = false
		_ = saveDLNAConfig(cfg)
		jsonResponse(w, map[string]interface{}{"success": false, "error": opErr.Error()})
		return
	}

	_ = saveDLNAConfig(cfg)
	jsonResponse(w, map[string]interface{}{
		"success": true,
		"enabled": cfg.Enabled,
	})
}

