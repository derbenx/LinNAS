// DLNAConfig represents DLNA server and caster preferences
type DLNAConfig struct {
	Enabled       bool   `json:"enabled"`
	ServerBackend string `json:"server_backend"` // "builtin" or "minidlna"
	MediaFolder   string `json:"media_folder"`
	FriendlyName  string `json:"friendly_name"`
	Port          int    `json:"port"`          // Port for built-in Go DLNA server (default 8200)
	StreamMode    string `json:"stream_mode"`   // "direct_http" or "dlna_content"
	UpdatedAt     string `json:"updated_at,omitempty"`
}

type DiscoveredRenderer struct {
	ID               string `json:"id"`
	FriendlyName     string `json:"friendly_name"`
	Manufacturer     string `json:"manufacturer,omitempty"`
	ModelName        string `json:"model_name,omitempty"`
	Location         string `json:"location"`
	AVTransportURL   string `json:"av_transport_url"`
	RenderingCtrlURL string `json:"rendering_ctrl_url"`
	IP               string `json:"ip"`
	LastSeen         int64  `json:"last_seen"`
}

