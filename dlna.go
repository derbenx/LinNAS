func getDLNAConfigPath() string {
	return filepath.Join(getBinaryDir(), "dlna.json")
}

func loadDLNAConfig() {
	dlnaConfigMu.Lock()
	defer dlnaConfigMu.Unlock()

	defaultMedia := "/var/media"
	if fi, err := os.Stat(defaultMedia); os.IsNotExist(err) || !fi.IsDir() {
		// Prefer existing directory like /home or working directory if /var/media does not exist
		if cwd, err := os.Getwd(); err == nil && cwd != "" {
			defaultMedia = cwd
		} else {
			defaultMedia = "/home"
		}
	}

	dlnaConfig = DLNAConfig{
		Enabled:       false,
		ServerBackend: "builtin",
		MediaFolder:   defaultMedia,
		FriendlyName:  "LinNAS DLNA",
		Port:          8200,
		StreamMode:    "direct_http",
	}

	b, err := os.ReadFile(getDLNAConfigPath())
	if err != nil || len(b) == 0 {
		b, err = os.ReadFile("html/dlna/data.json")
	}
	if err == nil && len(b) > 0 {
		var cfg DLNAConfig
		if err := json.Unmarshal(b, &cfg); err == nil {
			if cfg.ServerBackend != "builtin" && cfg.ServerBackend != "minidlna" {
				cfg.ServerBackend = "builtin"
			}
			if cfg.Port <= 0 {
				cfg.Port = 8200
			}
			if cfg.StreamMode == "" {
				cfg.StreamMode = "direct_http"
			}
			if cfg.FriendlyName == "" {
				cfg.FriendlyName = "LinNAS DLNA"
			}
			dlnaConfig = cfg
		}
	}
}

func saveDLNAConfig(cfg DLNAConfig) error {
	dlnaConfigMu.Lock()
	defer dlnaConfigMu.Unlock()

	cfg.UpdatedAt = time.Now().Format(time.RFC3339)
	b, err := json.MarshalIndent(cfg, "", "  ")
	if err != nil {
		return err
	}

	_ = os.WriteFile(getDLNAConfigPath(), b, 0644)
	_ = os.MkdirAll("html/dlna", 0755)
	_ = os.WriteFile("html/dlna/data.json", b, 0644)
	dlnaConfig = cfg
	return nil
}

