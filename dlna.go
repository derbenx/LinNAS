func handleDLNACast(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		http.Error(w, "Method not allowed", http.StatusMethodNotAllowed)
		return
	}

	bodyBytes, err := io.ReadAll(r.Body)
	if err != nil {
		http.Error(w, "Failed to read body", http.StatusBadRequest)
		return
	}
	decryptedBody, err := decryptPayload(bodyBytes)
	if err != nil {
		http.Error(w, fmt.Sprintf(`{"error":"decryption_failed: %v"}`, err), http.StatusBadRequest)
		return
	}

	var req struct {
		RendererID string `json:"renderer_id"`
		Action     string `json:"action"` // "play", "pause", "stop", "volume", "seek"
		FilePath   string `json:"file_path"`
		StreamMode string `json:"stream_mode"` // "direct_http" or "dlna_content"
		Volume     int    `json:"volume"`      // 0 - 100
		TargetTime string `json:"target_time"` // "00:01:23"
	}
	if err := json.Unmarshal(decryptedBody, &req); err != nil || req.RendererID == "" || req.Action == "" {
		http.Error(w, "Invalid request payload", http.StatusBadRequest)
		return
	}

	discoveredRenderersMu.RLock()
	renderer, exists := discoveredRenderers[req.RendererID]
	discoveredRenderersMu.RUnlock()

	if !exists || renderer.AVTransportURL == "" {
		// Try matching by IP or friendly name if exact ID isn't found
		matched := false
		discoveredRenderersMu.RLock()
		for _, rdr := range discoveredRenderers {
			if rdr.IP == req.RendererID || rdr.FriendlyName == req.RendererID {
				renderer = rdr
				matched = true
				break
			}
		}
		discoveredRenderersMu.RUnlock()

		if !matched {
			jsonResponse(w, map[string]interface{}{"success": false, "error": "Selected renderer device not found. Please refresh discovery."})
			return
		}
	}

	dlnaConfigMu.RLock()
	cfg := dlnaConfig
	dlnaConfigMu.RUnlock()

	serverIP := getPrimaryIP()
	streamMode := req.StreamMode
	if streamMode == "" {
		streamMode = cfg.StreamMode
	}

	switch strings.ToLower(req.Action) {
	case "play":
		// If a new file is specified, execute SetAVTransportURI first
		if req.FilePath != "" {
			var mediaURI string
			if streamMode == "dlna_content" {
				relFromMedia, _ := filepath.Rel(cfg.MediaFolder, req.FilePath)
				if !strings.HasPrefix(relFromMedia, "..") {
					mediaURI = fmt.Sprintf("http://%s:%d/media/%s", serverIP, cfg.Port, url.PathEscape(filepath.ToSlash(relFromMedia)))
				} else {
					mediaURI = fmt.Sprintf("http://%s:%d/api/fs/raw?path=%s", serverIP, appConfig.Port, url.QueryEscape(req.FilePath))
				}
			} else {
				// Direct HTTP stream from LinNAS core API endpoint
				mediaURI = fmt.Sprintf("http://%s:%d/api/fs/raw?path=%s", serverIP, appConfig.Port, url.QueryEscape(req.FilePath))
			}

			title := filepath.Base(req.FilePath)
			mimeType, dlnaProfile := getAudioMimeAndDLNAProfile(req.FilePath)
			currentURIMetaData := fmt.Sprintf(`<DIDL-Lite xmlns="urn:schemas-upnp-org:metadata-1-0/DIDL-Lite/" xmlns:dc="http://purl.org/dc/elements/1.1/" xmlns:upnp="urn:schemas-upnp-org:metadata-1-0/upnp/"><item id="1" parentID="0" restricted="1"><dc:title>%s</dc:title><upnp:class>object.item.audioItem.musicTrack</upnp:class><res protocolInfo="http-get:*:%s:%s">%s</res></item></DIDL-Lite>`,
				html.EscapeString(title), mimeType, dlnaProfile, html.EscapeString(mediaURI))

			setURIArgs := fmt.Sprintf("<InstanceID>0</InstanceID><CurrentURI>%s</CurrentURI><CurrentURIMetaData>%s</CurrentURIMetaData>",
				html.EscapeString(mediaURI), html.EscapeString(currentURIMetaData))

			_, _ = sendSOAPAction(renderer.AVTransportURL, "urn:schemas-upnp-org:service:AVTransport:1", "Stop", "<InstanceID>0</InstanceID>")
			time.Sleep(150 * time.Millisecond)
			_, _ = sendSOAPAction(renderer.AVTransportURL, "urn:schemas-upnp-org:service:AVTransport:1", "SetAVTransportURI", setURIArgs)
			time.Sleep(100 * time.Millisecond)
		}

		playArgs := "<InstanceID>0</InstanceID><Speed>1</Speed>"
		soapResp, err := sendSOAPAction(renderer.AVTransportURL, "urn:schemas-upnp-org:service:AVTransport:1", "Play", playArgs)
		if err != nil {
			jsonResponse(w, map[string]interface{}{"success": false, "error": err.Error()})
			return
		}
		jsonResponse(w, map[string]interface{}{"success": true, "response": soapResp})

	case "pause":
		pauseArgs := "<InstanceID>0</InstanceID>"
		soapResp, err := sendSOAPAction(renderer.AVTransportURL, "urn:schemas-upnp-org:service:AVTransport:1", "Pause", pauseArgs)
		if err != nil {
			jsonResponse(w, map[string]interface{}{"success": false, "error": err.Error()})
			return
		}
		jsonResponse(w, map[string]interface{}{"success": true, "response": soapResp})

	case "stop":
		stopArgs := "<InstanceID>0</InstanceID>"
		soapResp, err := sendSOAPAction(renderer.AVTransportURL, "urn:schemas-upnp-org:service:AVTransport:1", "Stop", stopArgs)
		if err != nil {
			jsonResponse(w, map[string]interface{}{"success": false, "error": err.Error()})
			return
		}
		jsonResponse(w, map[string]interface{}{"success": true, "response": soapResp})

	case "seek":
		if req.TargetTime == "" {
			req.TargetTime = "00:00:00"
		}
		seekArgs := fmt.Sprintf("<InstanceID>0</InstanceID><Unit>REL_TIME</Unit><Target>%s</Target>", html.EscapeString(req.TargetTime))
		soapResp, err := sendSOAPAction(renderer.AVTransportURL, "urn:schemas-upnp-org:service:AVTransport:1", "Seek", seekArgs)
		if err != nil {
			jsonResponse(w, map[string]interface{}{"success": false, "error": err.Error()})
			return
		}
		jsonResponse(w, map[string]interface{}{"success": true, "response": soapResp})

	case "volume":
		if renderer.RenderingCtrlURL == "" {
			jsonResponse(w, map[string]interface{}{"success": false, "error": "Renderer does not support volume control (RenderingControl missing)"})
			return
		}
		vol := req.Volume
		if vol < 0 {
			vol = 0
		}
		if vol > 100 {
			vol = 100
		}
		volArgs := fmt.Sprintf("<InstanceID>0</InstanceID><Channel>Master</Channel><DesiredVolume>%d</DesiredVolume>", vol)
		soapResp, err := sendSOAPAction(renderer.RenderingCtrlURL, "urn:schemas-upnp-org:service:RenderingControl:1", "SetVolume", volArgs)
		if err != nil {
			jsonResponse(w, map[string]interface{}{"success": false, "error": err.Error()})
			return
		}
		jsonResponse(w, map[string]interface{}{"success": true, "response": soapResp})

	default:
		jsonResponse(w, map[string]interface{}{"success": false, "error": "Unsupported cast action"})
	}
}

func handleDLNACastStatus(w http.ResponseWriter, r *http.Request) {
	rendererID := r.URL.Query().Get("renderer_id")
	if rendererID == "" {
		http.Error(w, "Missing renderer_id", http.StatusBadRequest)
		return
	}

	discoveredRenderersMu.RLock()
	renderer, exists := discoveredRenderers[rendererID]
	discoveredRenderersMu.RUnlock()

	if !exists || renderer.AVTransportURL == "" {
		jsonResponse(w, map[string]interface{}{"success": false, "error": "Renderer not found"})
		return
	}

	// 1. GetTransportInfo
	transInfo, _ := sendSOAPAction(renderer.AVTransportURL, "urn:schemas-upnp-org:service:AVTransport:1", "GetTransportInfo", "<InstanceID>0</InstanceID>")
	state := regexpExtract(transInfo, `<CurrentTransportState>([^<]+)</CurrentTransportState>`)
	status := regexpExtract(transInfo, `<CurrentTransportStatus>([^<]+)</CurrentTransportStatus>`)

	// 2. GetPositionInfo
	posInfo, _ := sendSOAPAction(renderer.AVTransportURL, "urn:schemas-upnp-org:service:AVTransport:1", "GetPositionInfo", "<InstanceID>0</InstanceID>")
	relTime := regexpExtract(posInfo, `<RelTime>([^<]+)</RelTime>`)
	trackDuration := regexpExtract(posInfo, `<TrackDuration>([^<]+)</TrackDuration>`)
	trackURI := regexpExtract(posInfo, `<TrackURI>([^<]+)</TrackURI>`)

	// 3. GetVolume
	currentVolume := -1
	if renderer.RenderingCtrlURL != "" {
		volResp, _ := sendSOAPAction(renderer.RenderingCtrlURL, "urn:schemas-upnp-org:service:RenderingControl:1", "GetVolume", "<InstanceID>0</InstanceID><Channel>Master</Channel>")
		if volStr := regexpExtract(volResp, `<CurrentVolume>([^<]+)</CurrentVolume>`); volStr != "" {
			if v, err := strconv.Atoi(volStr); err == nil {
				currentVolume = v
			}
		}
	}

	jsonResponse(w, map[string]interface{}{
		"success":        true,
		"state":          state,
		"status":         status,
		"rel_time":       relTime,
		"track_duration": trackDuration,
		"track_uri":      trackURI,
		"volume":         currentVolume,
	})
}
