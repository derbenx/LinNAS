func sendSOAPAction(controlURL, serviceType, actionName string, argsXML string) (string, error) {
	envelope := fmt.Sprintf(`<?xml version="1.0" encoding="utf-8"?>
<s:Envelope xmlns:s="http://schemas.xmlsoap.org/soap/envelope/" s:encodingStyle="http://schemas.xmlsoap.org/soap/encoding/">
  <s:Body>
    <u:%s xmlns:u="%s">
      %s
    </u:%s>
  </s:Body>
</s:Envelope>`, actionName, serviceType, argsXML, actionName)

	req, err := http.NewRequest(http.MethodPost, controlURL, strings.NewReader(envelope))
	if err != nil {
		return "", err
	}

	soapActionHeader := fmt.Sprintf(`"%s#%s"`, serviceType, actionName)
	req.Header.Set("Content-Type", `text/xml; charset="utf-8"`)
	req.Header.Set("SOAPAction", soapActionHeader)

	client := http.Client{Timeout: 5 * time.Second}
	resp, err := client.Do(req)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()

	outBytes, err := io.ReadAll(resp.Body)
	if err != nil {
		return "", err
	}
	return string(outBytes), nil
}

