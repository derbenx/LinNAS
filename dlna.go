func startSSDPAnnouncer(port int) {
	ssdpAdvMu.Lock()
	defer ssdpAdvMu.Unlock()

	if ssdpAdvStopChan != nil {
		close(ssdpAdvStopChan)
		ssdpAdvStopChan = nil
	}

	stopChan := make(chan struct{})
	ssdpAdvStopChan = stopChan

	go func() {
		raddr, err := net.ResolveUDPAddr("udp4", "239.255.255.250:1900")
		if err != nil {
			return
		}
		conn, err := net.DialUDP("udp4", nil, raddr)
		if err != nil {
			return
		}
		defer conn.Close()

		ticker := time.NewTicker(30 * time.Second)
		defer ticker.Stop()

		sendAlive := func() {
			hostIP := getPrimaryIP()
			location := fmt.Sprintf("http://%s:%d/description.xml", hostIP, port)
			usnList := []struct {
				nt  string
				usn string
			}{
				{"upnp:rootdevice", "uuid:2fac1234-31f8-11b4-a222-08002b34c003::upnp:rootdevice"},
				{"uuid:2fac1234-31f8-11b4-a222-08002b34c003", "uuid:2fac1234-31f8-11b4-a222-08002b34c003"},
				{"urn:schemas-upnp-org:device:MediaServer:1", "uuid:2fac1234-31f8-11b4-a222-08002b34c003::urn:schemas-upnp-org:device:MediaServer:1"},
				{"urn:schemas-upnp-org:service:ContentDirectory:1", "uuid:2fac1234-31f8-11b4-a222-08002b34c003::urn:schemas-upnp-org:service:ContentDirectory:1"},
				{"urn:schemas-upnp-org:service:ConnectionManager:1", "uuid:2fac1234-31f8-11b4-a222-08002b34c003::urn:schemas-upnp-org:service:ConnectionManager:1"},
			}

			for _, item := range usnList {
				msg := fmt.Sprintf("NOTIFY * HTTP/1.1\r\n"+
					"HOST: 239.255.255.250:1900\r\n"+
					"CACHE-CONTROL: max-age=1800\r\n"+
					"LOCATION: %s\r\n"+
					"NT: %s\r\n"+
					"NTS: ssdp:alive\r\n"+
					"SERVER: Linux/UPnP/1.0 DLNADOC/1.50 LinNAS/1.0\r\n"+
					"USN: %s\r\n\r\n", location, item.nt, item.usn)
				_, _ = conn.Write([]byte(msg))
			}
		}

		sendAlive()
		for {
			select {
			case <-stopChan:
				return
			case <-ticker.C:
				sendAlive()
			}
		}
	}()
}

